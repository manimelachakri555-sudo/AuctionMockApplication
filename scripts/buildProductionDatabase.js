// Fast URL verification
function verifyImageUrl(url) {
  return new Promise((resolve) => {
    try {
      const req = https.get(
        url,
        {
          headers: {
            'User-Agent':
              'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
            Accept: 'image/avif,image/webp,image/apng,image/svg+xml,image/*,*/*;q=0.8',
          },
          timeout: 6000,
        },
        (res) => {
          const ct = res.headers['content-type'] || '';
          const ok = (res.statusCode === 200 || res.statusCode === 304) && ct.includes('image');
          const len = parseInt(res.headers['content-length'] || '0');
          res.destroy();
          resolve({ ok, status: res.statusCode || 0, ct, len });
        }
      );
      req.on('error', () => resolve({ ok: false, status: 0, ct: '', len: 0 }));
      req.on('timeout', () => {
        req.destroy();
        resolve({ ok: false, status: 408, ct: '', len: 0 });
      });
    } catch (e) {
      resolve({ ok: false, status: 0, ct: '', len: 0 });
    }
  });
}

// Batch fetch Wikipedia thumbnails
async function getWikiThumbsBatch(titles) {
  const chunks = [];
  for (let i = 0; i < titles.length; i += 30) chunks.push(titles.slice(i, i + 30));
  const res = {};
  for (const c of chunks) {
    const url =
      'https://en.wikipedia.org/w/api.php?action=query&titles=' +
      encodeURIComponent(c.join('|')) +
      '&prop=pageimages&format=json&pithumbsize=500';
    await new Promise((done) => {
      https
        .get(url, { headers: { 'User-Agent': 'IPLProductionBuilder/2.0' } }, (r) => {
          let d = '';
          r.on('data', (chunk) => (d += chunk));
          r.on('end', () => {
            try {
              const j = JSON.parse(d);
              for (const pid in j.query.pages) {
                const p = j.query.pages[pid];
                if (p.thumbnail?.source) res[p.title] = p.thumbnail.source;
              }
            } catch (e) {}
            done();
          });
        })
        .on('error', () => done());
    });
  }
  return res;
}

